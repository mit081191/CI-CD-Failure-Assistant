"""Run all six agents on every scenario and save the results as submission evidence.

Usage:
    python run_all_scenarios.py                # all scenarios, qwen3:8b
    python run_all_scenarios.py --model qwen3:4b
    python run_all_scenarios.py --only A C     # selected scenario IDs

Writes results/scenario_<ID>.json (full agent outputs) and results/summary.md
(one comparison table per scenario). Requires Ollama running for the LLM agent;
if it is unavailable, the LLM row records the error and the classical results are still saved.
"""
import argparse
import json
import time
from datetime import datetime
from pathlib import Path

from scenarios import SCENARIOS
from agents.classical import (SimpleReflexAgent, ModelBasedReflexAgent, GoalBasedAgent,
                              UtilityBasedAgent, LearningAgent)
from agents.llm_agent import run_llm_agent

RESULTS_DIR = Path("results")


def run_scenario(scenario, model):
    results = {}
    for agent in [SimpleReflexAgent(), ModelBasedReflexAgent(), GoalBasedAgent(),
                  UtilityBasedAgent(), LearningAgent()]:
        results[agent.name] = agent.decide(scenario)
    start = time.perf_counter()
    try:
        results["LLM (Ollama)"] = run_llm_agent(scenario, model=model)
    except Exception as exc:  # keep the classical results even if Ollama fails
        results["LLM (Ollama)"] = {"failure_category": "LLM unavailable", "likely_cause": str(exc),
                                   "recommended_next_step": "", "confidence": 0.0, "tools_called": []}
    results["LLM (Ollama)"]["runtime_seconds"] = round(time.perf_counter() - start, 1)
    return results


def _cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def summary_table(name, results):
    lines = [f"## {name}", "",
             "| Agent | Failure category | Recommended next step | Confidence | LLM tools called |",
             "|---|---|---|---|---|"]
    for agent, r in results.items():
        tools = ", ".join(r.get("tools_called", [])) if "tools_called" in r else "-"
        lines.append(f"| {agent} | {_cell(r.get('failure_category', ''))} | "
                     f"{_cell(r.get('recommended_next_step', ''))} | {round(float(r.get('confidence', 0)), 2)} | {tools} |")
    llm = results["LLM (Ollama)"]
    lines += ["", f"LLM likely cause: {_cell(llm.get('likely_cause', ''))}",
              f"LLM runtime: {llm.get('runtime_seconds')} s", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--model", default="qwen3:8b")
    parser.add_argument("--only", nargs="*", help="Scenario IDs to run, e.g. N A B")
    args = parser.parse_args()

    RESULTS_DIR.mkdir(exist_ok=True)
    sections = []
    for name, scenario in SCENARIOS.items():
        sid = scenario["scenario_id"]
        if args.only and sid not in args.only:
            continue
        print(f"Running scenario {name} ...", flush=True)
        results = run_scenario(scenario, args.model)
        out = {"scenario": name, "model": args.model,
               "run_at": datetime.now().isoformat(timespec="seconds"),
               "input": scenario, "results": results}
        (RESULTS_DIR / f"scenario_{sid}.json").write_text(json.dumps(out, indent=2), encoding="utf-8")
        sections.append(summary_table(name, results))
        llm = results["LLM (Ollama)"]
        print(f"  LLM: {llm.get('failure_category')} | tools={llm.get('tools_called')} | "
              f"{llm.get('runtime_seconds')} s", flush=True)

    header = (f"# Scenario results\n\nGenerated by `run_all_scenarios.py` on "
              f"{datetime.now():%Y-%m-%d %H:%M} with model `{args.model}`. "
              "Full agent outputs are in the matching `scenario_<ID>.json` files.\n\n")
    (RESULTS_DIR / "summary.md").write_text(header + "\n".join(sections), encoding="utf-8")
    print(f"Saved results to {RESULTS_DIR.resolve()}")


if __name__ == "__main__":
    main()
